  `SpellID` int unsigned NOT NULL, `Gender` tinyint unsigned NOT NULL DEFAULT 2, `DisplayID` int unsigned NOT NULL,
  PRIMARY KEY (`SpellID`,`Gender`,`DisplayID`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
-- Collections: items that teach a toy (0), mount (1) or companion (2). Learned spells are shared by the whole account when Temucraft.LostLands.AccountWideCollections = 1.
CREATE TABLE IF NOT EXISTS `mod_temucraft_lostlands_collection` (
  `ItemID` int unsigned NOT NULL, `SpellID` int unsigned NOT NULL, `Type` tinyint unsigned NOT NULL DEFAULT 0,
  PRIMARY KEY (`ItemID`,`SpellID`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
-- Per-spawn object scale (gameobject guid), applied when the object is added to the world.
CREATE TABLE IF NOT EXISTS `mod_temucraft_lostlands_spawn_scale` (
  `Guid` int unsigned NOT NULL, `Scale` float NOT NULL DEFAULT 1, PRIMARY KEY (`Guid`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
-- Quest objectives completed by casting a spell on another player: credit goes to the quest's RequiredNpcOrGo of that objective.
-- TargetClass 0 = any class; TargetGM 1 = the target must be a game master.
CREATE TABLE IF NOT EXISTS `mod_temucraft_lostlands_quest_cast` (
  `QuestID` int unsigned NOT NULL, `ObjectiveIndex` tinyint unsigned NOT NULL, `SpellID` int unsigned NOT NULL,
  `TargetClass` tinyint unsigned NOT NULL DEFAULT 0, `TargetGM` tinyint unsigned NOT NULL DEFAULT 0, `Comment` varchar(100) NOT NULL DEFAULT '',
  PRIMARY KEY (`QuestID`,`ObjectiveIndex`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
